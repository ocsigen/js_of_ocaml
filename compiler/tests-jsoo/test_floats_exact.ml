(* Exact ties for values outside the exact integer paths below (n >= 2^64),
   where the digits come from toExponential/toFixed *)
let%expect_test "exact ties, large expansions" =
  p "%.19e" (ldexp 1. (-30));
  p "%.29f" (ldexp 1. (-30));
  p "%.20g" (ldexp 1. (-30));
  p "%.1e" 1.25e20;
  p "%.2g" 1.25e20;
  [%expect
    {|
           9.3132257461547851562e-10
           0.00000000093132257461547851562
           9.3132257461547851562e-10
           1.2e+20
           1.2e+20
           |}]

