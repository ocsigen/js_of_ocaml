(* toFixed and toExponential round exact ties away from zero; C rounds them
   to even. *)
let%expect_test "exact ties" =
  p "%.17g" 90.0351715087890625;
  p "%.2f" 0.125;
  p "%.0f" 2.5;
  p "%.0f" 3.5;
  p "%.0e" 25.;
  p "%.2e" 0.5625;
  p "%.3g" 0.5625;
  p "%.10g" 0.65673828125;
  [%expect
    {|
    90.035171508789062
    0.12
    2
    4
    2e+01
    5.62e-01
    0.562
    0.6567382812
    |}]

