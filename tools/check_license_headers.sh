#!/bin/sh
# Check that the source files of the compiler, the libraries and the runtime
# start with the standard LGPL license header:
#
#   <title, one of a fixed list (see below)>
#   http://www.ocsigen.org/js_of_ocaml/
#   <optional lines: Copyright (C) <year>[-<year>] <holder>>
#   <blank line>
#   <license notice, verbatim>
#
# Only files tracked by git are considered. Tests are skipped. Files that are
# generated, or that are adapted from third-party code and keep its license
# notice, are listed explicitly below; this list should not grow for any other
# reason.
#
# Usage: tools/check_license_headers.sh
set -u

cd "$(dirname "$0")/.." || exit 2

is_exempt() {
  case "$1" in
    # Tests
    */tests/* | */tests-*/*) return 0 ;;
    # Generated by gen_stubs.exe (dune rules in promote mode)
    compiler/lib-dynlink*/stubs.c | *_stubs.c) return 0 ;;
    # Adapted from the OCaml distribution (LGPL, with its own notice)
    compiler/lib/build_path_prefix_map.ml*) return 0 ;;
    compiler/lib/strongly_connected_components.ml*) return 0 ;;
    runtime/js/lexing.js | runtime/js/parsing.js) return 0 ;;
    # Adapted from pfff (LGPL, with its own notice)
    compiler/lib/parse_js.ml) return 0 ;;
    # Adapted from other third-party code, which comes with its own license
    compiler/lib/base64.ml | compiler/lib/base64.mli) return 0 ;; # ISC
    compiler/lib/flow_lexer.ml | compiler/lib/flow_lexer.mli) return 0 ;; # MIT
    lib/deriving_json/deriving_Json_lexer.ml[il]) return 0 ;; # BSD
    runtime/js/blake2.js | runtime/js/zstd.js) return 0 ;;
    runtime/wasm/c/blake2.h | runtime/wasm/c/blake2-impl.h) return 0 ;; # BLAKE2
    runtime/wasm/c/blake2b-ref.c) return 0 ;; # BLAKE2 reference code
    runtime/wasm/c/zstddeclib.c) return 0 ;; # zstd reference code
  esac
  return 1
}

files=$(git ls-files -- \
  'compiler/lib*' 'compiler/bin-*' lib ppx runtime toplevel/bin 'toplevel/lib*' |
  grep -E '\.(ml|mli|mll|mly|js|wat|c|h)$' |
  while read -r f; do is_exempt "$f" || echo "$f"; done)

if [ -z "$files" ]; then
  echo "No file to check: is this a git checkout?" >&2
  exit 2
fi

# shellcheck disable=SC2086
awk '
BEGIN {
  n = split( \
    "This program is free software; you can redistribute it and/or modify\n" \
    "it under the terms of the GNU Lesser General Public License as published by\n" \
    "the Free Software Foundation, with linking exception;\n" \
    "either version 2.1 of the License, or (at your option) any later version.\n" \
    "\n" \
    "This program is distributed in the hope that it will be useful,\n" \
    "but WITHOUT ANY WARRANTY; without even the implied warranty of\n" \
    "MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the\n" \
    "GNU Lesser General Public License for more details.\n" \
    "\n" \
    "You should have received a copy of the GNU Lesser General Public License\n" \
    "along with this program; if not, write to the Free Software\n" \
    "Foundation, Inc., 59 Temple Place - Suite 330, Boston, MA 02111-1307, USA.", \
    notice, "\n")
  title_list = "\"Js_of_ocaml compiler\", " \
    "\"Js_of_ocaml library\", " \
    "\"Js_of_ocaml runtime support\", " \
    "\"Js_of_ocaml toplevel runtime support\", " \
    "\"Wasm_of_ocaml compiler\", " \
    "\"Wasm_of_ocaml runtime support\""
  m = split(title_list, t, /", "|"/)
  for (k = 1; k <= m; k++) if (t[k] != "") titles[t[k]] = 1
  url = "http://www.ocsigen.org/js_of_ocaml/"
  year = "[0-9][0-9][0-9][0-9]"
  copyright = "^Copyright \\(C\\) " year "(-" year ")? [^ -]"
  # Historical affiliation line, allowed after a copyright line
  affiliation = "Laboratoire PPS - CNRS Université Paris Diderot"
}

function fail(msg) {
  printf "%s:%d: %s\n", FILENAME, FNR, msg
  errors++
  state = "done"
}

function finish() {
  if (file != "" && state != "done") {
    printf "%s: truncated license header\n", file
    errors++
  }
}

FNR == 1 {
  finish()
  file = FILENAME
  checked++
  state = "title"
}

state == "done" { next }

{
  # Strip the comment markers: "(* ", "/* ", " * ", " *)", "// ", ";; "
  line = $0
  sub(/[ \t]*\*\)[ \t]*$/, "", line)
  sub(/^[ \t]*(\(\*|\/\*|\*|\/\/|;;)/, "", line)
  sub(/^ /, "", line)
  sub(/[ \t]+$/, "", line)
}

state == "title" {
  # Header section of ocamllex files, start of a C comment
  if (FNR == 1 && ($0 == "{" || $0 == "/*")) next
  if (line in titles) state = "url"
  else fail("expected the license header, starting with one of: " title_list)
  next
}

state == "url" {
  if (line == url) { state = "copyright"; ncopyright = 0 }
  else fail("expected \"" url "\"")
  next
}

state == "copyright" {
  if (line == "") { state = "notice"; i = 1 }
  else if (line ~ copyright) ncopyright++
  else if (line == affiliation && ncopyright > 0) { }
  else fail("expected \"Copyright (C) <year>[-<year>] <holder>\", or a blank line " \
            "followed by the license notice")
  next
}

state == "notice" {
  if (line != notice[i]) fail("expected \"" notice[i] "\"")
  else if (++i > n) state = "done"
  next
}

END {
  finish()
  if (errors) {
    printf "\n%d error(s) in the license headers of %d files.\n", errors, checked
    print "Copy the header from a neighbouring file, or, for generated or"
    print "third-party files, add an exemption to tools/check_license_headers.sh."
    exit 1
  }
  printf "All %d files have a license header.\n", checked
}' $files
